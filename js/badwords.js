/* 短词查表（O(1)） */
const BAD_WORDS_SHORT_MAP = (function () {
  const m = Object.create(null);
  for (const w of BAD_WORDS_SHORT) m[w] = w;
  return m;
})();

/* 归一化 —— 用来挡住常见的绕过手法
 *   ① 全角 → 半角      ＳＢ → sb
 *   ② 去掉空白和标点    傻 ？逼 → 傻逼
 *   ③ 统一小写         SB → sb
 *   ④ 连续重复压成一个   操操操 → 操
 * 这样"操 操-操"、"Ｓ Ｂ"这类写法都会被还原后再比对。 */
function badwordNormalize(s) {
  let t = String(s == null ? '' : s);
  t = t.replace(/[\uFF01-\uFF5E]/g, function (ch) {
    return String.fromCharCode(ch.charCodeAt(0) - 0xFEE0);
  });
  t = t.replace(/[^\u4e00-\u9fa5a-zA-Z0-9]/g, '');
  t = t.toLowerCase();
  t = t.replace(/(.)\1+/g, '$1');
  return t;
}

/* 命中检测：命中返回那个词，没命中返回 null */
function badwordHit(name) {
  const n = badwordNormalize(name);
  if (!n) return null;
  if (BAD_WORDS_SHORT_MAP[n]) return BAD_WORDS_SHORT_MAP[n];
  for (let i = 0; i < BAD_WORDS_LONG.length; i++) {
    if (n.indexOf(BAD_WORDS_LONG[i]) >= 0) return BAD_WORDS_LONG[i];
  }
  return null;
}

/* 昵称校验：返回 { ok, msg }
 * 顺序：先查长度和字符，再查敏感词 —— 这样报错信息更具体。 */
const NICK_MAX = 10;
function checkNickname(name) {
  const raw = String(name == null ? '' : name);
  const trimmed = raw.trim();

  if (!trimmed) return { ok: false, msg: '名字不能为空' };
  if (Array.from(trimmed).length > NICK_MAX) {
    return { ok: false, msg: '名字最多 ' + NICK_MAX + ' 个字' };
  }
  /* 只允许中文、字母、数字，以及中间的分隔符 */
  if (/[^\u4e00-\u9fa5a-zA-Z0-9 _\-·]/.test(trimmed)) {
    return { ok: false, msg: '名字只能用中文、字母、数字（可以有 - _ ·）' };
  }
  if (/^[ _\-·]|[ _\-·]$/.test(trimmed)) {
    return { ok: false, msg: '名字不能以符号开头或结尾' };
  }
  if (/[ _\-·]{2,}/.test(trimmed)) {
    return { ok: false, msg: '名字里不能有连续的符号' };
  }
  const hit = badwordHit(trimmed);
  if (hit) return { ok: false, msg: '这个名字不合适，换一个吧' };
  return { ok: true, msg: '' };
}

